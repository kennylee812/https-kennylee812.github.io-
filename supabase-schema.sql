drop policy if exists "authenticated update labor masters" on public.labor_masters;
create policy "authenticated update labor masters" on public.labor_masters
  for update to authenticated using (true) with check (true);
drop policy if exists "authenticated delete labor masters" on public.labor_masters;
create policy "authenticated delete labor masters" on public.labor_masters
